"""Render a sample result page to docs/sample-report.html.

Runs the agent end to end against the scripted offline client, so the output is
a real render of a real trace — not a mockup — and costs nothing to regenerate.
The README links to it so a reviewer can see what the tool produces without
running anything.

    python scripts/render_sample.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

os.environ.setdefault("ANTHROPIC_API_KEY", "sk-offline-sample")
os.environ.setdefault("DB_PATH", ":memory:")

from fastapi.testclient import TestClient  # noqa: E402

from app import config  # noqa: E402
from app.agent.client import FakeClient  # noqa: E402
from app.corpus.index import CorpusIndex  # noqa: E402
from tests.fakes import full_run_script  # noqa: E402

JD = (ROOT / "tests" / "fixtures" / "sample_jd.txt").read_text()
OUT = ROOT / "docs" / "sample-report.html"


def main() -> None:
    config.reset_settings_cache()
    from app.main import app

    index = CorpusIndex.from_directory(str(ROOT / "app" / "corpus" / "documents"))

    with TestClient(app) as client:
        app.state.client_factory = lambda: FakeClient(full_run_script(index))
        html = client.post("/analyse", data={"jd_text": JD}).text

    # Inline the stylesheet so the file stands alone in a browser or a PR.
    css = (ROOT / "app" / "static" / "style.css").read_text()
    html = html.replace(
        '<link rel="stylesheet" href="/static/style.css">',
        f"<style>\n{css}\n</style>",
    )
    banner = (
        '<p style="max-width:1000px;margin:0 auto;padding:10px 20px;font:13px system-ui;'
        'opacity:.7">Static sample, generated by <code>scripts/render_sample.py</code> '
        "from the offline scripted client. The numbers and trace below are a real run.</p>"
    )
    html = html.replace("<body>", "<body>\n" + banner, 1)

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(html)
    print(f"wrote {OUT} ({len(html):,} bytes)")


if __name__ == "__main__":
    main()
